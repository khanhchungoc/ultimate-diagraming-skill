          for (const el of hiddenWhile) el.style.opacity = '';
          hiddenWhile.clear();
          if (svgJob) { cancelAnimationFrame(svgJob.raf); applySvgJob(svgJob, 1); svgJob = null; }
          if (ghostLayer) ghostLayer.textContent = '';
