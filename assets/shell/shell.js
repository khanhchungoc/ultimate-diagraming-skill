                el.setAttribute('y1', fromBuf[o + 1] + (toBuf[o + 1] - fromBuf[o + 1]) * p);
                el.setAttribute('x2', fromBuf[o + 2] + (toBuf[o + 2] - fromBuf[o + 2]) * p);
